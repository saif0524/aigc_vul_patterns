const int MOD = 1e9 + 7;

long long mod_exp(long long base, long long exp) {
    long long result = 1;
    base %= MOD;
    while (exp > 0) {
        if (exp % 2 == 1) result = (result * base) % MOD;
        exp >>= 1;
        base = (base * base) % MOD;
    }
    return result;
}

