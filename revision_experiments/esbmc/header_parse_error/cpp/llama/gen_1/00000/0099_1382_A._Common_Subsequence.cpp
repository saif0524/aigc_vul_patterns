using namespace std;

int main() {
    int t;
    cin >> t;
    while (t--) {
        int n, m;
        cin >> n >> m;
        vector<int> a(n), b(m);
        for (int i = 0; i < n; i++) cin >> a[i];
        for (int i = 0; i < m; i++) cin >> b[i];
        vector<int> c;
        for (int i = 0; i < n; i++) {
            for (int j = 0; j < m; j++) {
                if (a[i] == b[j]) {
                    c.push_back(a[i]);
                    break;
                }
            }
        }
        if (c.empty()) cout << "NO\n";
        else {
            cout << "YES\n";
            cout << 1 << " " << c[0] << "\n";
        }
    }
    return 0;
}